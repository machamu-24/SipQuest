/**
 * 入力テキストに基づいてサジェスト候補をフィルタリングする
 */
export function filterOriginSuggestions(
  drinkType: DrinkTypeValue,
  input: string,
): readonly string[] {
  if (!input.trim()) {
    return ORIGIN_SUGGESTIONS[drinkType].slice(0, 8);
  }

  const normalized = input.trim().toLowerCase().normalize("NFKC");
  return ORIGIN_SUGGESTIONS[drinkType].filter((suggestion) =>
    suggestion.toLowerCase().normalize("NFKC").includes(normalized),
  );
}
